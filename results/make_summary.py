"""Grid summary for the ternary concept gate (CONCEPT-GATE.md), generated from the raw records.

    python results/make_summary.py --logs <logs dir> --runs <runs dir> [--out results/GRID-SUMMARY.md]

Reads, per cell: <logs>/<cell>-eval.jsonl (eval set + game cells), <logs>/<cell>-onnx.json (the file),
<logs>/<cell>-verify.json (file = evaluated model), <runs>/<cell>/variant.json (bits per weight), and the v1
reference cell <logs>/v1-reference.jsonl. Missing cells are listed as pending.
"""
from __future__ import annotations

import argparse
import datetime
import json
from pathlib import Path

CELLS = [("v2-ternary-b243-ptq", "Base243", "PTQ of v2"), ("v2-ternary-t34-ptq", "T34", "PTQ of v2"),
         ("v2-ternary-b243-qat", "Base243", "QAT from v2"), ("v2-ternary-t34-qat", "T34", "QAT from v2"),
         ("v3-ternary-b243", "Base243", "from scratch (v3)"), ("v3-ternary-t34", "T34", "from scratch (v3)")]
# Extra cells (SWEEP-PLAN.md), outside the six-cell grid; listed when their records exist, the gate applied the same way
EXTRA = [("v2-ternary-b243-qat-attn-int8", "Base243", "QAT from v2, attention int8 (extra)"),
         ("v2-ternary-t34-qat-attn-int8", "T34", "QAT from v2, attention int8 (extra)"),
         ("v3-ternary-t34-seed8", "T34", "from scratch (v3), second seed (extra)"),
         ("v3-ternary-t34-long", "T34", "from scratch (v3), stage 2 twice as long (extra)")]
V2 = {"bot:4": 0.915, "bot:6": 0.893, "vp": 0.9872}  # the dense model, PROTOCOL-v2 records (RESULTS-R0)


def load_jsonl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text().splitlines() if l.strip()] if p.exists() else []


def cell_record(logs: Path, runs: Path, name: str) -> dict | None:
    rows = load_jsonl(logs / f"{name}-eval.jsonl")
    if not rows:
        return None
    ev = next((r for r in rows if "value_preserving" in r and "a" not in r), None)
    games = {(r["b"].split("/")[-1], r["seed"]): r for r in rows if "a_score" in r}
    rec = {"eval": ev, "games": games}
    for key, fname in (("onnx", f"{name}-onnx.json"), ("verify", f"{name}-verify.json")):
        p = logs / fname
        rec[key] = json.loads(p.read_text()) if p.exists() and p.read_text().strip() else None
    v = runs / name / "variant.json"
    rec["variant"] = json.loads(v.read_text()) if v.exists() else None
    return rec


def fmt_ci(r: dict | None) -> str:
    if not r:
        return "-"
    lo, hi = r["a_score_ci"]
    return f"{r['a_score']:.3f} [{lo:.3f}-{hi:.3f}]"


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--logs", type=Path, required=True)
    p.add_argument("--runs", type=Path, required=True)
    p.add_argument("--out", type=Path, default=Path(__file__).with_name("GRID-SUMMARY.md"))
    a = p.parse_args()
    v1 = load_jsonl(a.logs / "v1-reference.jsonl")
    v1ref = v1[0] if v1 else None
    v1_hi = v1ref["a_score_ci"][1] if v1ref else None

    lines = [f"# GRID-SUMMARY: the ternary Connect Four grid (generated {datetime.date.today()})", "",
             "Generated by `results/make_summary.py` from the raw records; the gate is CONCEPT-GATE.md (sha256",
             "`b738b105...`).", "",
             f"v1 reference cell (v1 vs bot:4, same harness, PROTOCOL-v2 rules): **{fmt_ci(v1ref)}**." if v1ref else
             "v1 reference cell: pending.", "",
             "## Concept gate", "",
             "| cell | format | regime | file bytes | < 2 MB and file = evaluated model | vs v1 (> 0.5) | vs bot:4, interval above v1's | **gate** |",
             "| --- | --- | --- | ---: | :---: | --- | --- | :---: |"]
    strong = ["", "## Strong bars (production reference, not a gate here) and eval-set metrics", "",
              "| cell | vs bot:4 | vs bot:6 | value-preserving (>= 0.97) | VP non-trivial | exact top-1 | owner shuffle drop | mirror |",
              "| --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
              f"| v2 (dense, reference) | {V2['bot:4']:.3f} | {V2['bot:6']:.3f} | {V2['vp']:.4f} | 0.970 | 0.935 | 0.49 | 0.77 |"]
    size = ["", "## Size and bits per weight", "",
            "| cell | file bytes | gzip bytes | graph + functions | tensor bytes | bits/weight, ternary codes | + scales | all parameters | ternary weight rel. RMS error vs v2 |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
    games_t = ["", "## All game cells (score, 95 % Wilson interval; 200 games, 0.05 noise, empty board)", "",
               "| cell | bot:2 | bot:4 s2026 | bot:4 s2027 | bot:4 s2028 | bot:6 s2026 | bot:6 s2027 | bot:6 s2028 | random | v1 | solver |",
               "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    extra = [c for c in EXTRA if (a.logs / f"{c[0]}-eval.jsonl").exists()]
    for name, fmt, regime in CELLS + extra:
        r = cell_record(a.logs, a.runs, name)
        if not r:
            lines.append(f"| `{name}` | {fmt} | {regime} | - | - | - | - | pending |")
            continue
        g = r["games"]
        onnx, ver = r["onnx"] or {}, r["verify"] or {}
        c1 = bool(onnx.get("bytes") and onnx["bytes"] < 2_000_000 and ver.get("all_same"))
        h2h = next((v for (b, s), v in g.items() if "onepass-c4-8x24" in b and s == 2026), None)
        c2 = bool(h2h and h2h["a_score"] > 0.5)
        b4 = g.get(("bot:4", 2026))
        c3 = bool(b4 and v1_hi is not None and b4["a_score_ci"][0] > v1_hi)
        gate = "PASS" if c1 and c2 and c3 else "fail"
        yes = lambda ok: "yes" if ok else "**no**"
        lines.append(f"| `{name}` | {fmt} | {regime} | {onnx.get('bytes', '-')} | {yes(c1)} | {fmt_ci(h2h)} {yes(c2)} | "
                     f"{fmt_ci(b4)} {yes(c3)} | **{gate}** |")
        ev = r["eval"] or {}
        strong.append(f"| `{name}` | {fmt_ci(b4)} | {fmt_ci(g.get(('bot:6', 2026)))} | {ev.get('value_preserving', 0):.4f} | "
                      f"{ev.get('value_preserving_nontrivial', 0):.3f} | {ev.get('exact_top1', 0):.3f} | "
                      f"{ev.get('control_owner_shuffle_drop_nt', 0):.2f} | {ev.get('control_mirror', 0):.2f} |")
        v = r["variant"] or {}
        bpw = v.get("bits_per_weight", {})
        err = (v.get("relative_rms_error") or {}).get("ternary")
        size.append(f"| `{name}` | {onnx.get('bytes', '-')} | {onnx.get('gzip_bytes', '-')} | {onnx.get('graph_and_function_bytes', '-')} | "
                    f"{v.get('tensor_bytes', '-')} | {bpw.get('ternary_codes', '-')} | {bpw.get('ternary_codes_and_scales', '-')} | "
                    f"{bpw.get('all_parameters', '-')} | {err:.3f} |" if err is not None else
                    f"| `{name}` | {onnx.get('bytes', '-')} | - | - | - | - | - | - | - |")
        cols = [g.get(("bot:2", 2026)), g.get(("bot:4", 2026)), g.get(("bot:4", 2027)), g.get(("bot:4", 2028)),
                g.get(("bot:6", 2026)), g.get(("bot:6", 2027)), g.get(("bot:6", 2028)), g.get(("random", 2026)), h2h,
                g.get(("solver", 2026))]
        games_t.append(f"| `{name}` | " + " | ".join(fmt_ci(c) for c in cols) + " |")
    notes = ["", "## Notes", "",
             "- \"file = evaluated model\": ONNX Runtime runs the file through its FunctionProto reference decode and chooses the",
             "  same column as the dense evaluation on all 17 325 eval positions (`export/verify_onnx.py`).",
             "- For QAT and v3 cells the evaluated model is the best checkpoint by quantized value-preserving rate on the",
             "  validation set, exported with the same `ptq/variant.py` as the PTQ cells.",
             "- The ternary weight error column compares with v2's weights; for v3 (trained from scratch) it is not meaningful.",
             "- Extra cells (SWEEP-PLAN.md) are not part of the pre-registered grid; the gate columns are applied to them",
             "  the same way for comparison.",
             "", "## Post-training sweeps (2026-09-28)", "",
             "60 training-free variants of v2 around the PTQ cells: `results/SWEEP-SUMMARY.md` (plan: `SWEEP-PLAN.md`).",
             "In short: the least-squares scale is too small for the model's function (least-squares scale x1.2 takes",
             "Base243 PTQ from VP 0.920 to 0.965; a Lloyd-Max scale takes T34 PTQ from 0.13 to 0.81 against bot:4);",
             "attention q/k/v is the sensitive family; group size barely matters; absmean is the worst fit."]
    a.out.write_text("\n".join(lines + strong + size + games_t + notes) + "\n")
    print(a.out.read_text())


if __name__ == "__main__":
    main()
