"""SWEEP-SUMMARY.md from the raw sweep records (SWEEP-PLAN.md).

    python results/make_sweep_summary.py [--records results/records/sweep] [--out results/SWEEP-SUMMARY.md]

Per variant: <name>.jsonl (the eval-set line, then the bot:4 game line) and <name>-variant.json.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
FORMATS = {"b243": "Base243", "t34": "T34"}
FAMILIES = ("qkv", "out", "up", "down", "opt")
FAMILY_TEXT = {"qkv": "attention q/k/v", "out": "attention out", "up": "MLP up", "down": "MLP down",
               "opt": "option encoder"}


def load(records: Path) -> dict:
    out = {}
    for path in sorted(records.glob("*.jsonl")):
        name = path.stem
        lines = [json.loads(x) for x in path.read_text().splitlines() if x.strip()]
        ev = next((x for x in lines if "value_preserving" in x and "a_score" not in x), None)
        game = next((x for x in lines if x.get("b") == "bot:4"), None)
        variant = records / f"{name}-variant.json"
        out[name] = {"eval": ev, "game": game, "variant": json.loads(variant.read_text()) if variant.exists() else None}
    return out


def row(label: str, r: dict | None, base_vp: float | None = None) -> str:
    if not r or not r["eval"] or not r["game"]:
        return f"| {label} | not run | | | | | |"
    ev, game, var = r["eval"], r["game"], r["variant"]
    lo, hi = game["a_score_ci"]
    size = f"{var['tensor_bytes'] / 1e6:.2f} MB, {var['bits_per_weight']['all_parameters']:.2f}" if var else "7.38 M fp32"
    delta = f"{ev['value_preserving'] - base_vp:+.4f}" if base_vp is not None else ""
    return (f"| {label} | {size} | {ev['value_preserving']:.4f} | {delta} | {ev['value_preserving_nontrivial']:.3f} | "
            f"{ev['exact_top1']:.3f} | {game['a_score']:.3f} [{lo:.3f}-{hi:.3f}] |")


HEAD = ("| variant | tensors, bits per parameter | value-preserving | vs no ternary | VP non-trivial | exact top-1 | "
        "vs bot:4 [95 %] |\n| --- | --- | ---: | ---: | ---: | ---: | --- |")


def main() -> None:
    p = argparse.ArgumentParser()
    p.add_argument("--records", type=Path, default=HERE / "records" / "sweep")
    p.add_argument("--out", type=Path, default=HERE / "SWEEP-SUMMARY.md")
    a = p.parse_args()
    R = load(a.records)
    none = R.get("sweep-none")
    base = none["eval"]["value_preserving"] if none and none["eval"] else None
    s = ["# SWEEP-SUMMARY: post-training sweeps around the ternary grid", "",
         "Generated by `results/make_sweep_summary.py` from the raw records in `results/records/sweep/`; the plan is",
         "SWEEP-PLAN.md. Every variant is converted from v2 without training. Eval set: 17 325 positions. Game: vs bot:4,",
         "seed 2026, 200 games, PROTOCOL-v2 rules. \"vs no ternary\" is the change in value-preserving rate against",
         "`sweep-none` (only the int8 and fp16 roles, no ternary matrices).",
         "", "## References", "", HEAD,
         row("v2 dense (fp32)", R.get("sweep-v2-dense"), base),
         row("no ternary matrices (int8 embedding and head, fp16 rest)", none, base)]
    for f, fname in FORMATS.items():
        g = lambda n: R.get(f"sweep-{f}-{n}")  # noqa: E731
        s += ["", f"## {fname}", "", "### S1: group size (least squares, all 36 matrices)", "", HEAD]
        s += [row(f"G{n}" + (" (the grid PTQ cell)" if n == 128 else ""), g(f"g{n}"), base) for n in (64, 128, 256)]
        s += ["", "### S2: fitting method (G128, all 36 matrices)", "", HEAD, row("least squares (the grid)", g("g128"), base)]
        s += [row(m, g(m), base) for m in ("absmean", "lloydmax")]
        s += ["", "### S3: sensitivity (G128, least squares; the other matrices fp16)", "", HEAD]
        s += [row(f"only {FAMILY_TEXT[t]} ternary", g(f"only-{t}"), base) for t in FAMILIES]
        s += [row(f"all but {FAMILY_TEXT[t]} ternary", g(f"except-{t}"), base) for t in FAMILIES]
        s += [row(f"only context layers {i} and {i + 1} ternary", g(f"only-L{i}L{i + 1}"), base) for i in (0, 2, 4, 6)]
        s += ["", "### S4 and S5: allocations and combinations", "", HEAD,
              row("attention int8, MLP ternary", g("attn-int8"), base)]
        s += [row(n.replace(f"sweep-{f}-", ""), R[n], base) for n in sorted(R)
              if n.startswith(f"sweep-{f}-protect-") or (n.startswith(f"sweep-{f}-g") and n.count("-") == 3)]
    s += ["", "## S6 (post-hoc): why the Lloyd-Max scale helps", "",
          "Added after S2 (SWEEP-PLAN.md addendum). G128, all 36 matrices; the least-squares zeros unless noted,",
          "with other scales.", ""]
    for f, fname in FORMATS.items():
        g = lambda n: R.get(f"sweep-{f}-{n}")  # noqa: E731
        s += [f"### {fname}", "", HEAD, row("least squares (scale x1.0, the grid)", g("g128"), base)]
        s += [row(f"least-squares scale x{x}", g(f"ls-x{x}"), base) for x in ("1.1", "1.2", "1.3", "1.4")]
        s += [row("energy-preserving scale (the group keeps its norm)", g("rms"), base),
              row("Lloyd-Max (its own zeros and scale)", g("lloydmax"), base),
              row("Lloyd-Max on q/k/v only, least squares elsewhere", g("lloydmax-qkv-only"), base),
              row("Lloyd-Max everywhere except q/k/v", g("lloydmax-except-qkv"), base), ""]
    a.out.write_text("\n".join(s) + "\n")
    print(f"wrote {a.out} ({len(R)} variants)")


if __name__ == "__main__":
    main()
